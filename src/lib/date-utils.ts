export function isJapaneseHoliday(date: Date): boolean {
  const dateStr = toJSTDate(date).toISOString().split("T")[0]
  return dateStr in JAPAN_HOLIDAYS_2024_2027
}

export function isWeekday(date: Date): boolean {
  const jstDate = toJSTDate(date)
  const day = jstDate.getDay()
  return day >= 1 && day <= 5 // Monday to Friday
}

export function isBusinessDay(date: Date): boolean {
  return isWeekday(date) && !isJapaneseHoliday(date)
}

export function toJSTDate(date: Date = new Date()): Date {
  // Convert to JST (UTC+9)
  const utcTime = date.getTime()
  const jstOffset = 9 * 60 * 60 * 1000 // 9 hours in milliseconds
  return new Date(utcTime + jstOffset)
}

export function getJSTDateString(date: Date = new Date()): string {
  const jstDate = toJSTDate(date)
  return jstDate.toISOString().split("T")[0]
}
